"""Agent execution engine — runs agents through their full lifecycle.

This orchestrates the actual execution of each agent:
1. PLAN: Agent uses LLM to decompose its goal into sub-tasks
2. EXECUTE: Run tools, analyze outputs, spawn children
3. AGGREGATE: Collect child results and combine findings
4. REFLECT: Analyze what worked and update strategy
5. REPORT: Produce final result

Each step involves LLM calls with optimized prompts
containing KB context, experience, and hierarchy info.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Any

import structlog

from recursec.agents.recursive_agent_core import (
    AgentRole,
    RecursiveAgent,
    RecursiveAgentManager,
    ROLE_CONFIG,
)

logger = structlog.get_logger()


class ExecutionPhase(str, Enum):
    INIT = "init"
    PLAN = "plan"
    SELECT_TOOLS = "select_tools"
    EXECUTE_TOOLS = "execute_tools"
    ANALYZE_OUTPUT = "analyze_output"
    SPAWN_CHILDREN = "spawn_children"
    WAIT_CHILDREN = "wait_children"
    AGGREGATE = "aggregate"
    VALIDATE = "validate"
    REFLECT = "reflect"
    REPORT = "report"
    DONE = "done"


# Valid phase transitions
PHASE_TRANSITIONS: dict[ExecutionPhase, list[ExecutionPhase]] = {
    ExecutionPhase.INIT: [ExecutionPhase.PLAN],
    ExecutionPhase.PLAN: [ExecutionPhase.SELECT_TOOLS, ExecutionPhase.SPAWN_CHILDREN],
    ExecutionPhase.SELECT_TOOLS: [ExecutionPhase.EXECUTE_TOOLS],
    ExecutionPhase.EXECUTE_TOOLS: [ExecutionPhase.ANALYZE_OUTPUT, ExecutionPhase.SELECT_TOOLS],
    ExecutionPhase.ANALYZE_OUTPUT: [ExecutionPhase.SPAWN_CHILDREN, ExecutionPhase.VALIDATE, ExecutionPhase.SELECT_TOOLS, ExecutionPhase.REPORT],
    ExecutionPhase.SPAWN_CHILDREN: [ExecutionPhase.WAIT_CHILDREN],
    ExecutionPhase.WAIT_CHILDREN: [ExecutionPhase.AGGREGATE],
    ExecutionPhase.AGGREGATE: [ExecutionPhase.VALIDATE, ExecutionPhase.REPORT],
    ExecutionPhase.VALIDATE: [ExecutionPhase.REFLECT],
    ExecutionPhase.REFLECT: [ExecutionPhase.REPORT],
    ExecutionPhase.REPORT: [ExecutionPhase.DONE],
}


@dataclass
class ExecutionStep:
    """A single step in the execution pipeline."""
    step_id: int = 0
    phase: ExecutionPhase = ExecutionPhase.INIT
    action: str = ""
    input_data: dict[str, Any] = field(default_factory=dict)
    output_data: dict[str, Any] = field(default_factory=dict)
    model_used: str = ""
    tokens_used: int = 0
    duration_ms: float = 0.0
    success: bool = True
    error: str = ""
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> dict[str, Any]:
        return {
            "step": self.step_id,
            "phase": self.phase.value[:10],
            "action": self.action[:20],
            "ok": self.success,
            "tokens": self.tokens_used,
            "ms": f"{self.duration_ms:.0f}",
        }


@dataclass
class ExecutionPlan:
    """Plan generated by the planner LLM for an agent's goal."""
    agent_id: str = ""
    goal: str = ""
    sub_tasks: list[dict[str, Any]] = field(default_factory=list)
    tools_needed: list[str] = field(default_factory=list)
    children_needed: list[dict[str, str]] = field(default_factory=list)
    estimated_steps: int = 10
    strategy: str = "breadth_first"

    def to_dict(self) -> dict[str, Any]:
        return {
            "goal": self.goal[:25],
            "sub_tasks": len(self.sub_tasks),
            "tools": len(self.tools_needed),
            "children": len(self.children_needed),
            "strategy": self.strategy[:15],
        }


