class AgentExecutionEngine:
    """Runs agents through their execution lifecycle."""

    def __init__(self, manager: RecursiveAgentManager | None = None) -> None:
        self._manager = manager or RecursiveAgentManager()
        self._execution_steps: dict[str, list[ExecutionStep]] = {}
        self._plans: dict[str, ExecutionPlan] = {}
        self._step_counter = 0
        self._log = logger.bind(component="execution_engine")

    @property
    def manager(self) -> RecursiveAgentManager:
        return self._manager

    def build_plan_prompt(self, agent: RecursiveAgent) -> str:
        """Build the planning prompt for an agent."""
        role_config = ROLE_CONFIG.get(agent.role, {})
        template = PLAN_PROMPTS.get(agent.role, DEFAULT_PLAN_PROMPT)

        parent_findings_text = ""
        if agent.context.parent_findings:
            parent_findings_text = "\n".join(
                f"  - {f.get('title', 'N/A')} [{f.get('severity', 'info')}]"
                for f in agent.context.parent_findings[:10]
            )

        return template.format(
            goal=agent.goal,
            target=agent.context.target,
            tools=", ".join(role_config.get("tools", [])),
            parent_findings=parent_findings_text or "None yet",
            parent_context=str(agent.context.shared_context)[:500],
            role=agent.role.value,
        )

    def build_tool_select_prompt(self, agent: RecursiveAgent, executed: list[str]) -> str:
        """Build prompt for selecting the next tool."""
        role_config = ROLE_CONFIG.get(agent.role, {})
        return TOOL_SELECT_PROMPT.format(
            phase=agent.context.phase,
            goal=agent.goal,
            target=agent.context.target,
            tools=", ".join(role_config.get("tools", [])),
            executed_tools=", ".join(executed) or "none",
            findings_count=len(agent.findings),
        )

    def build_analysis_prompt(self, tool: str, output: str, target: str) -> str:
        """Build prompt for analyzing tool output."""
        return ANALYSIS_PROMPT.format(
            tool=tool,
            target=target,
            output=output[:4000],
        )

    def record_step(
        self,
        agent_id: str,
        phase: ExecutionPhase,
        action: str,
        input_data: dict[str, Any] | None = None,
        output_data: dict[str, Any] | None = None,
        model_used: str = "",
        tokens_used: int = 0,
        success: bool = True,
        error: str = "",
    ) -> ExecutionStep:
        """Record an execution step."""
        self._step_counter += 1
        step = ExecutionStep(
            step_id=self._step_counter,
            phase=phase,
            action=action,
            input_data=input_data or {},
            output_data=output_data or {},
            model_used=model_used,
            tokens_used=tokens_used,
            success=success,
            error=error,
        )

        if agent_id not in self._execution_steps:
            self._execution_steps[agent_id] = []
        self._execution_steps[agent_id].append(step)

        # Update agent budgets
        agent = self._manager._agents.get(agent_id)
        if agent:
            agent.token_budget.consume(input_tokens=tokens_used // 2, output_tokens=tokens_used // 2)
            self._manager.record_action(agent_id, action)

        return step

    def store_plan(self, agent_id: str, plan: ExecutionPlan) -> None:
        """Store the execution plan for an agent."""
        self._plans[agent_id] = plan

    def get_plan(self, agent_id: str) -> ExecutionPlan | None:
        """Get the stored plan for an agent."""
        return self._plans.get(agent_id)

    def check_should_continue(self, agent_id: str) -> tuple[bool, str]:
        """Check if agent should continue executing."""
        agent = self._manager._agents.get(agent_id)
        if not agent:
            return False, "agent_not_found"

        # Budget checks
        if agent.token_budget.exhausted:
            return False, "token_budget_exhausted"
        if agent.step_budget.exhausted:
            return False, "step_budget_exhausted"

        # Convergence check
        if self._manager.check_convergence(agent_id):
            return False, "converged_or_stuck"

        # Time limit (10 min per agent)
        if agent.elapsed_s > 600:
            return False, "timeout"

        return True, "ok"

    def get_execution_trace(self, agent_id: str) -> list[dict[str, Any]]:
        """Get the full execution trace for an agent."""
        steps = self._execution_steps.get(agent_id, [])
        return [s.to_dict() for s in steps]

    def get_stats(self) -> dict[str, Any]:
        total_steps = sum(len(s) for s in self._execution_steps.values())
        total_tokens = sum(
            sum(s.tokens_used for s in steps)
            for steps in self._execution_steps.values()
        )
        return {
            "agents_tracked": len(self._execution_steps),
            "total_steps": total_steps,
            "total_tokens": total_tokens,
            "plans_stored": len(self._plans),
            "manager_stats": self._manager.get_stats(),
        }

    def build_execution_context_prompt(self, agent_id: str) -> str:
        """Build a prompt with the full execution context for an agent."""
        agent = self._manager._agents.get(agent_id)
        if not agent:
            return ""

        lines = []

        # Hierarchy context
        hierarchy = self._manager.build_hierarchy_prompt(agent_id)
        if hierarchy:
            lines.append(hierarchy)

        # Execution trace summary
        steps = self._execution_steps.get(agent_id, [])
        if steps:
            lines.append(f"\n## Execution History ({len(steps)} steps)")
            for step in steps[-5:]:
                status = "OK" if step.success else "FAIL"
                lines.append(f"  [{status}] {step.phase.value}: {step.action[:40]}")

        # Current plan
        plan = self._plans.get(agent_id)
        if plan:
            completed_tasks = sum(1 for t in plan.sub_tasks if t.get("completed"))
            lines.append(f"\n## Plan Progress: {completed_tasks}/{len(plan.sub_tasks)} sub-tasks")

        # Budget status
        should_continue, reason = self.check_should_continue(agent_id)
        if not should_continue:
            lines.append(f"\n⚠ STOPPING: {reason}")

        return "\n".join(lines)
